using BugManagement.Api.Data;
using BugManagement.Api.Dtos;
using BugManagement.Api.Models;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;

namespace BugManagement.Api.Controllers;

/// <summary>
/// REST API controller managing Bug reports.
/// Provides CRUD operations: Create, Read (all/single), Update, and Delete.
/// </summary>
[ApiController]
[Route("api/[controller]")]
[Produces("application/json")]
public class BugsController : ControllerBase
{
    private readonly ApplicationDbContext _context;
    private readonly ILogger<BugsController> _logger;

    public BugsController(ApplicationDbContext context, ILogger<BugsController> logger)
    {
        _context = context;
        _logger = logger;
    }

    /// <summary>
    /// Retrieves all reported bugs ordered by report date descending.
    /// </summary>
    /// <returns>A list of bug response objects.</returns>
    /// <response code="200">Returns list of reported bugs.</response>
    [HttpGet]
    [ProducesResponseType(typeof(IEnumerable<BugResponseDto>), StatusCodes.Status200OK)]
    public async Task<ActionResult<IEnumerable<BugResponseDto>>> GetAllBugs()
    {
        _logger.LogInformation("Fetching all reported bugs.");

        var bugs = await _context.Bugs
            .AsNoTracking()
            .OrderByDescending(b => b.ReportDate)
            .Select(b => ToResponseDto(b))
            .ToListAsync();

        return Ok(bugs);
    }

    /// <summary>
    /// Retrieves a single bug by its unique identifier.
    /// </summary>
    /// <param name="id">The unique bug ID.</param>
    /// <returns>The bug response object if found.</returns>
    /// <response code="200">Bug found and returned.</response>
    /// <response code="404">No bug found with the specified ID.</response>
    [HttpGet("{id:int}")]
    [ProducesResponseType(typeof(BugResponseDto), StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<ActionResult<BugResponseDto>> GetBugById(int id)
    {
        _logger.LogInformation("Fetching bug with ID {BugId}.", id);

        var bug = await _context.Bugs
            .AsNoTracking()
            .FirstOrDefaultAsync(b => b.Id == id);

        if (bug == null)
        {
            _logger.LogWarning("Bug with ID {BugId} was not found.", id);
            return NotFound(new { message = $"Bug with ID {id} was not found." });
        }

        return Ok(ToResponseDto(bug));
    }

    /// <summary>
    /// Creates a new bug report.
    /// Note: The ReportDate is automatically assigned by the server.
    /// </summary>
    /// <param name="dto">Bug creation details.</param>
    /// <returns>The newly created bug response object with Location header.</returns>
    /// <response code="201">Bug created successfully.</response>
    /// <response code="400">Invalid input parameters.</response>
    [HttpPost]
    [ProducesResponseType(typeof(BugResponseDto), StatusCodes.Status201Created)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    public async Task<ActionResult<BugResponseDto>> CreateBug([FromBody] CreateBugDto dto)
    {
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        _logger.LogInformation("Creating new bug: {BugName}", dto.BugName);

        var bug = new Bug
        {
            BugName = dto.BugName.Trim(),
            BugDescription = dto.BugDescription.Trim(),
            Level = dto.Level,
            // ReportDate must be automatically generated by the backend
            ReportDate = DateTime.UtcNow
        };

        _context.Bugs.Add(bug);
        await _context.SaveChangesAsync();

        _logger.LogInformation("Successfully created bug with ID {BugId}.", bug.Id);

        var responseDto = ToResponseDto(bug);

        return CreatedAtAction(
            nameof(GetBugById),
            new { id = bug.Id },
            responseDto
        );
    }

    /// <summary>
    /// Updates an existing bug's name, description, and severity level.
    /// </summary>
    /// <param name="id">The ID of the bug to update.</param>
    /// <param name="dto">Updated bug information.</param>
    /// <returns>The updated bug object.</returns>
    /// <response code="200">Bug updated successfully.</response>
    /// <response code="400">Validation failed or invalid ID.</response>
    /// <response code="404">No bug found with the specified ID.</response>
    [HttpPut("{id:int}")]
    [ProducesResponseType(typeof(BugResponseDto), StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<ActionResult<BugResponseDto>> UpdateBug(int id, [FromBody] UpdateBugDto dto)
    {
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        _logger.LogInformation("Updating bug with ID {BugId}.", id);

        var bug = await _context.Bugs.FindAsync(id);

        if (bug == null)
        {
            _logger.LogWarning("Bug with ID {BugId} was not found for update.", id);
            return NotFound(new { message = $"Bug with ID {id} was not found." });
        }

        bug.BugName = dto.BugName.Trim();
        bug.BugDescription = dto.BugDescription.Trim();
        bug.Level = dto.Level;
        // Notice: ReportDate is preserved as the original creation timestamp

        await _context.SaveChangesAsync();

        _logger.LogInformation("Successfully updated bug with ID {BugId}.", bug.Id);

        return Ok(ToResponseDto(bug));
    }

    /// <summary>
    /// Deletes a bug report by its ID.
    /// </summary>
    /// <param name="id">The ID of the bug to delete.</param>
    /// <returns>No content on success.</returns>
    /// <response code="204">Bug successfully deleted.</response>
    /// <response code="404">No bug found with the specified ID.</response>
    [HttpDelete("{id:int}")]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> DeleteBug(int id)
    {
        _logger.LogInformation("Attempting to delete bug with ID {BugId}.", id);

        var bug = await _context.Bugs.FindAsync(id);

        if (bug == null)
        {
            _logger.LogWarning("Bug with ID {BugId} was not found for deletion.", id);
            return NotFound(new { message = $"Bug with ID {id} was not found." });
        }

        _context.Bugs.Remove(bug);
        await _context.SaveChangesAsync();

        _logger.LogInformation("Successfully deleted bug with ID {BugId}.", id);

        return NoContent();
    }

    /// <summary>
    /// Helper mapper method from Bug entity to BugResponseDto.
    /// </summary>
    private static BugResponseDto ToResponseDto(Bug bug) => new()
    {
        Id = bug.Id,
        BugName = bug.BugName,
        BugDescription = bug.BugDescription,
        ReportDate = bug.ReportDate,
        Level = bug.Level
    };
}

